#!/usr/bin/env node
// Emit Studio's base/reset layer (everything that is NOT a per-element sd-N/symbol-N/modal rule),
// scoped under .sd-root, minus the Font Awesome / Material Icons payload the page never renders.
import fs from 'node:fs';
import path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname);
const css = fs.readFileSync(path.join(here, '../css/main.css'), 'utf8');
const out = process.argv[2];

const chunks = [];
let depth = 0, start = 0;
for (let i = 0; i < css.length; i++) {
  if (css[i] === '{') depth++;
  else if (css[i] === '}') { depth--; if (depth === 0) { chunks.push(css.slice(start, i + 1)); start = i + 1; } }
}
const PER_ELEMENT = /\.(sd-\d|symbol-\d|list-\d|modal-|go\d)/;
const DROP = /Font Awesome|fontawesome|\.fa-/i;
const splitTop = (sel) => {
  const parts = []; let d = 0, cur = '';
  for (const ch of sel) {
    if (ch === '(' || ch === '[') d++;
    else if (ch === ')' || ch === ']') d--;
    if (ch === ',' && d === 0) { parts.push(cur); cur = ''; } else cur += ch;
  }
  parts.push(cur);
  return parts;
};
const scope = (sel) => splitTop(sel).map(s => {
  s = s.trim();
  if (!s) return s;
  if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)/, m => `${m}:has(.sd-root)`);
  if (/^:root|^:host/.test(s)) return s;
  return `.sd-root ${s}`;
}).join(', ');

const emit = (chunk) => {
  const i = chunk.indexOf('{');
  return scope(chunk.slice(0, i)) + ' ' + chunk.slice(i);
};
const kept = [];
for (const raw of chunks) {
  const t = raw.trim();
  if (!t || DROP.test(t)) continue;
  if (t.startsWith('@media') || t.startsWith('@supports') || t.startsWith('@container')) {
    const head = t.slice(0, t.indexOf('{') + 1);
    const body = t.slice(t.indexOf('{') + 1, t.lastIndexOf('}'));
    const inner = []; let d = 0, s0 = 0;
    for (let i = 0; i < body.length; i++) {
      if (body[i] === '{') d++;
      else if (body[i] === '}') { d--; if (d === 0) { inner.push(body.slice(s0, i + 1)); s0 = i + 1; } }
    }
    const ik = inner.filter(r => { const s = r.slice(0, r.indexOf('{')); return !PER_ELEMENT.test(s) && !DROP.test(r); });
    if (ik.length) kept.push(head + '\n' + ik.map(emit).join('\n') + '\n}');
    continue;
  }
  if (t.startsWith('@font-face')) {
    // Keep the Material Icons face (the carousel controls render its ligatures), rehomed to /public.
    if (/Material Icons/.test(t)) {
      kept.push(t.replace(/url\((['"]?)https:\/\/[^)'"]*MaterialIcons-Regular\.woff2\1\)/,
        "url('/sites/studio-design-8a86c0e4/shared/fonts/MaterialIcons-Regular.woff2')"));
    }
    continue;
  }
  if (t.startsWith('@charset') || t.startsWith('@import')) continue;
  if (t.startsWith('@')) continue;
  const sel = t.slice(0, t.indexOf('{'));
  if (PER_ELEMENT.test(sel)) continue;
  kept.push(emit(t));
}
const res = `/* Studio base layer, sliced from studio.design/ja/editor and scoped to .sd-root.\n   Generated by docs/research/studio-design-8a86c0e4/ja-editor-e6688fbb/tools/gen-base-css.mjs — do not hand-edit. */\n` + kept.join('\n') + '\n';
fs.writeFileSync(out, res);
console.log(JSON.stringify({ rules: kept.length, bytes: res.length, out }));

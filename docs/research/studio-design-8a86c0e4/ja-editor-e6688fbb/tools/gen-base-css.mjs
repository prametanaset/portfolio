#!/usr/bin/env node
// Emit Studio's base layer — everything that is NOT a per-element sd-N / symbol-N / modal rule —
// scoped under .sd-root, with the icon @font-face rules rehomed to /public.
// usage: node gen-base-css.mjs app/studio-base.css
import fs from 'node:fs';
import path from 'node:path';
import { splitBlocks, transformBlock } from './css-lib.mjs';

const here = path.dirname(new URL(import.meta.url).pathname);
const css = fs.readFileSync(path.join(here, '../css/main.css'), 'utf8');
const out = process.argv[2];
if (!out) { console.error('usage: gen-base-css.mjs <out.css>'); process.exit(1); }

// Per-page element rules stay out of the base layer. `modal-ja_menu` is this page's own dialog;
// the generic `.modal-container` / `.modal-backdrop` / `dialog[data-modal-transition-base]` rules
// are Studio's modal runtime and DO belong here.
const PER_ELEMENT = /\.(sd-\d|symbol-\d|list-\d|modal-ja_menu|go\d)/;
const FONT_DIR = '/sites/studio-design-8a86c0e4/shared/fonts';
const localFontFace = (block) =>
  block.replace(
    /url\((['"]?)https:\/\/[^)'"]*\/(MaterialIcons-Regular\.woff2|fa-solid-900\.woff2|fa-brands-400\.woff2)\1\)/g,
    (_m, _q, file) => `url('${FONT_DIR}/${file}')`,
  );

const kept = [];
for (const block of splitBlocks(css)) {
  const t = block.trim();
  if (!t) continue;
  if (t.startsWith('@font-face')) {
    // Keep only the icon faces the page actually renders; they now ship from /public.
    if (/Material Icons|Font Awesome/.test(t)) kept.push(localFontFace(t));
    continue;
  }
  // The origin registers --g-angle / --g-color-N / --g-position-N with @property. Without those
  // registrations the properties are not animatable and every gradient transition on the page
  // (the footer and mobile-menu curtain wipes, the header's hover fills) silently does nothing.
  if (t.startsWith('@property')) { kept.push(t); continue; }
  const transformed = transformBlock(t, (sel) => !PER_ELEMENT.test(sel));
  if (transformed) kept.push(transformed);
}

const result =
  `/* Studio base layer, sliced from studio.design/ja/editor and scoped to .sd-root.\n` +
  `   Generated by docs/research/studio-design-8a86c0e4/ja-editor-e6688fbb/tools/gen-base-css.mjs — do not hand-edit. */\n` +
  kept.join('\n') + '\n';
fs.writeFileSync(out, result);
console.log(JSON.stringify({ rules: kept.length, bytes: result.length, out }));
